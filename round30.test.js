'use strict'
/**
 * round30 · 「同一格内多人说话」的边界锁定
 *
 * 背景：宝哥对真实文档《建华&小凤的生活》81-90.docx 做多人同格专项检测后，
 * 全稿 49 个多人同格全部正确，但**本文档没出现的边界写法**里查出一条真缺陷：
 * 两人齐声的「A、B：…」被当成「B 单独说话」，切出「王建华、」这样的半句残词。
 *
 * 根因是两条规则打架：说话人左边界只要求「前一字符非中文」，而顿号/连接词
 * 恰好满足这一条 —— 于是并列结构被误当切点。本文件锁定修复后的行为：
 *
 *   30-A 并列连接 + 名字 + 冒号 = 联合说话人，整组不切开（不再产生残句）
 *   30-B 切点左移：联合组前面若接着正文（真粘连），切点移到**组的最前面**
 *   30-C 连接词左侧不是名字 → 切点作废（那是正文里的并列标点，不是联合说话人）
 *   30-D 与引号引用、普通多人的边界互不干扰
 *   30-E 白名单「优先」不等于「越权」：名字在白名单里也不许切开联合组
 *   30-F 端到端：docx 表格稿走完整链路，行数与零丢字都对
 */
const util = require('./miniprogram/utils/util.js')

let pass = 0
let fail = 0
function ok(name, cond, extra) {
  if (cond) { pass++; console.log('PASS | ' + name + (extra ? '  -> ' + extra : '')) }
  else { fail++; console.log('FAIL | ' + name + (extra ? '  -> ' + extra : '')) }
}
const squash = (s) => String(s || '').replace(/\s/g, '')
const J = (a) => JSON.stringify(a)
// 本稿已知说话人白名单（真实链路由 collectSpeakerNames 预扫得到）
const NAMES = { 王建华: 5, 杨凤: 5, 儿子: 2, 婆婆: 2, 李阿姨: 2 }
const split = (t) => util.splitDialogueCell(t, NAMES)

// ============================================================
console.log('\n=== 30-A. 联合说话人：并列连接 + 名字 + 冒号 → 整组不切开 ===')
// ============================================================
ok('A1 「A、B：」整行不拆（不再切出「王建华、」残词）',
  J(split('王建华、杨凤：我们一起回来了。')) === J(['王建华、杨凤：我们一起回来了。']),
  J(split('王建华、杨凤：我们一起回来了。')))

ok('A2 「A和B：」不拆', J(split('王建华和杨凤：我们一起回来了。')) === J(['王建华和杨凤：我们一起回来了。']))

ok('A3 「A还有B：」不拆', J(split('王建华还有杨凤：我们一起回来了。')) === J(['王建华还有杨凤：我们一起回来了。']))

ok('A4 「A以及B：」不拆', J(split('王建华以及杨凤：我们一起回来了。')) === J(['王建华以及杨凤：我们一起回来了。']))

ok('A5 「A跟B：」不拆', J(split('王建华跟杨凤：我们一起回来了。')) === J(['王建华跟杨凤：我们一起回来了。']))

ok('A6 联合组带括号动作「A、B（齐声）：」不拆',
  J(split('王建华、杨凤（齐声）：我们一起回来了。')) === J(['王建华、杨凤（齐声）：我们一起回来了。']))

ok('A7 括注写法「A、（B）：」不拆（切点左移到 A 之前）',
  J(split('王建华、（杨凤）：我们一起回来了。')) === J(['王建华、（杨凤）：我们一起回来了。']))

ok('A8 联合组在段首时切点=0，不产生空行',
  split('王建华、杨凤：我们一起回来了。').every((x) => x.trim().length > 0))

ok('A9 三人联合「A、B、C：」整组不拆',
  J(split('王建华、杨凤、婆婆：我们一起回来了。')) === J(['王建华、杨凤、婆婆：我们一起回来了。']))

ok('A10 零丢字：联合行拆后压平与原文一致',
  squash(split('王建华、杨凤（齐声）：我们一起回来了。').join('')) === squash('王建华、杨凤（齐声）：我们一起回来了。'))

// ============================================================
console.log('\n=== 30-B. 切点左移：联合组前接正文（真粘连）时，切点在组的最前面 ===')
// ============================================================
ok('B1 「…正文 + A、B：」切成两行，且第一行不含 A 的名字',
  J(split('杨凤：追剧还儿子、王建华：明天还得早起。')) ===
  J(['杨凤：追剧还', '儿子、王建华：明天还得早起。']),
  J(split('杨凤：追剧还儿子、王建华：明天还得早起。')))

ok('B2 左移后零丢字',
  squash(split('杨凤：追剧还儿子、王建华：明天还得早起。').join('')) ===
  squash('杨凤：追剧还儿子、王建华：明天还得早起。'))

ok('B3 左移同样适用于连接词「和」',
  J(split('杨凤：追剧还儿子和婆婆：明天还得早起。')) ===
  J(['杨凤：追剧还', '儿子和婆婆：明天还得早起。']))

ok('B4 左移同样适用于括注「（名字）：」',
  J(split('杨凤：追剧还儿子、（婆婆）：明天还得早起。')) ===
  J(['杨凤：追剧还', '儿子、（婆婆）：明天还得早起。']))

ok('B5 左移不会把名字切一半（「王建华、杨凤」不会变成「王」+「建华、杨凤」）',
  split('杨凤：追剧还王建华、杨凤：明天还得早起。')[1].indexOf('王建华、杨凤：') === 0,
  J(split('杨凤：追剧还王建华、杨凤：明天还得早起。')))

ok('B6 已有换行边界时，两段各自独立判定，互不影响',
  J(split('杨凤：追剧还\n儿子、王建华：明天还得早起。')) ===
  J(['杨凤：追剧还', '儿子、王建华：明天还得早起。']))

// ============================================================
console.log('\n=== 30-C. 连接词左侧不是名字 → 切点作废（正文里的并列标点）===')
// ============================================================
ok('C1 「正文…、 + 名字：」不切（「了菜」不是名字，那个顿号属正文）',
  J(split('杨凤：他买了菜、王建华：我不去。')) === J(['杨凤：他买了菜、王建华：我不去。']),
  J(split('杨凤：他买了菜、王建华：我不去。')))

ok('C2 「正文…和 + 名字：」里「和」左侧不是名字 → 不切',
  J(split('杨凤：他跟我说了和建华：我不去。')) === J(['杨凤：他跟我说了和建华：我不去。']))

ok('C3 作废分支同样零丢字',
  squash(split('杨凤：他买了菜、王建华：我不去。').join('')) === squash('杨凤：他买了菜、王建华：我不去。'))

ok('C4 没有白名单时不因「可能是联合组」而误伤正常切分',
  J(util.splitDialogueCell('杨凤：你吃几串了？王建华：才3串。')) === J(['杨凤：你吃几串了？', '王建华：才3串。']))

// ============================================================
console.log('\n=== 30-D. 与引号引用、普通多人互不干扰 ===')
// ============================================================
ok('D1 引号内的「名字：」是引用内容，不切',
  J(split('杨凤：他跟我说“王建华：我不去”，你信吗？')) === J(['杨凤：他跟我说“王建华：我不去”，你信吗？']))

ok('D2 嵌套引号内的「名字：」也不切',
  J(split('杨凤：妈说“你问他‘建华：我不去’”，你信吗？')) === J(['杨凤：妈说“你问他‘建华：我不去’”，你信吗？']))

ok('D3 普通两人（句末标点相隔）正常切',
  J(split('杨凤：你吃几串了？王建华：才3串。')) === J(['杨凤：你吃几串了？', '王建华：才3串。']))

ok('D4 正文中间的顿号不影响后面的切分',
  J(split('杨凤：我买了菜、肉。王建华：知道了。')) === J(['杨凤：我买了菜、肉。', '王建华：知道了。']))

ok('D5 正文里的「和」不是连接词，后接说话人照常切',
  J(split('杨凤：我买了菜和肉。王建华：知道了。')) === J(['杨凤：我买了菜和肉。', '王建华：知道了。']))

ok('D6 三人同段不受新规则影响',
  J(split('杨凤：一。王建华：二。婆婆：三。')) === J(['杨凤：一。', '王建华：二。', '婆婆：三。']))

ok('D7 真粘连（无并列连接）仍靠白名单救回',
  J(split('杨凤：你吃几串了王建华：才3串。')) === J(['杨凤：你吃几串了', '王建华：才3串。']))

// ============================================================
console.log('\n=== 30-E. 白名单「优先」不等于「越权」 ===')
// ============================================================
ok('E1 两个名字都在白名单里，联合组仍不许切开',
  J(split('王建华、杨凤：我们一起回来了。')) === J(['王建华、杨凤：我们一起回来了。']))

ok('E2 无白名单时同样不切开（不依赖上下文也稳）',
  J(util.splitDialogueCell('王建华、杨凤：我们一起回来了。')) === J(['王建华、杨凤：我们一起回来了。']))

ok('E3 白名单只认「本稿当过说话人」的名字：连接词左侧是陌生词时不左移',
  J(util.splitDialogueCell('杨凤：追剧还大漂亮、王建华：明天还得早起。', { 杨凤: 1, 王建华: 1 })) ===
  J(['杨凤：追剧还大漂亮、王建华：明天还得早起。']))

// ============================================================
console.log('\n=== 30-F. 端到端：docx 表格稿走完整链路 ===')
// ============================================================
const tc = (x) => '<w:tc><w:p><w:t>' + x + '</w:t></w:p></w:tc>'
const tcBr = (a, b) => '<w:tc><w:p><w:t>' + a + '</w:t><w:br/><w:t>' + b + '</w:t></w:p></w:tc>'
const xml =
  '<w:document><w:body>' +
  '<w:p><w:t>建华&小凤的生活91</w:t></w:p>' +
  '<w:tbl>' +
  '<w:tr>' + ['镜头', '画面', '台词', '备注'].map(tc).join('') + '</w:tr>' +
  // 第 1、2 格：先让「儿子」「王建华」以行首说话人身份出现 → 进白名单
  '<w:tr>' + tc('1') + tc('客厅') + tcBr('儿子：作业写完了没有。', '王建华：还没呢。') + tc('无') + '</w:tr>' +
  // 第 3 格：真粘连 + 联合说话人（切点必须左移到「儿子」之前）
  '<w:tr>' + tc('2') + tc('厨房') + tc('杨凤：追剧还儿子、王建华：明天还得早起。') + tc('无') + '</w:tr>' +
  // 第 4 格：段首联合（整组不切开）
  '<w:tr>' + tc('3') + tc('客厅') + tc('王建华、杨凤：我们一起回来了。') + tc('无') + '</w:tr>' +
  '</w:tbl></w:body></w:document>'

const res = util.splitScripts(util.extractDocxBlocks(xml))
const lines = res.ok && res.segments.length ? res.segments[0].lines : []
const flat = lines.map((x) => (typeof x === 'string' ? x : x.text)).map(squash)

ok('F1 拆集成功且只有一集', res.ok && res.segments.length === 1)
ok('F2 行数正确：2 + 2 + 1 = 5 行', flat.length === 5, '实际 ' + flat.length + ' 行 ' + J(flat))
ok('F3 真粘连 + 联合行被正确断开（不是粘成一行）',
  flat.indexOf(squash('杨凤：追剧还')) >= 0 &&
  flat.indexOf(squash('儿子、王建华：明天还得早起。')) >= 0)
ok('F4 段首联合行整行保留，无「王建华、」残词',
  flat.indexOf(squash('王建华、杨凤：我们一起回来了。')) >= 0)
ok('F5 端到端零丢字',
  squash(lines.map((x) => (typeof x === 'string' ? x : x.text)).join('')) ===
  squash('儿子：作业写完了没有。王建华：还没呢。杨凤：追剧还儿子、王建华：明天还得早起。王建华、杨凤：我们一起回来了。'))

// ============================================================
console.log('\n=== 汇总 ===')
console.log('round30 结果：' + pass + ' / ' + (pass + fail) + ' 通过' + (fail ? '，失败 ' + fail : ''))
process.exit(fail ? 1 : 0)
