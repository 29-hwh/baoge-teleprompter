'use strict'
/**
 * 表格稿样本（docx OOXML）——紧凑 spec + 生成器。
 *
 * 为什么要这样：docx 表格 XML 冗长，直接写 XML 不可读也不可维护。
 * 这里用「段落 / 表格行」的紧凑结构描述样本，再生成与真实 docx 同构的
 * document.xml，交给产品的 extractDocxBlocks → splitScripts 走完整链路。
 *
 * 每个 spec：
 *   blocks: [ {p:'第81集'} | {table:[[cell,...],...]} ]   // 顺序即文档顺序
 * 单元格文本里的 '\n' 会被渲染成 <w:br/>（段内软换行），用于测「同格多人」。
 */

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function wPara(text) {
  if (text === '' || text == null) return '<w:p/>'
  return '<w:p><w:r><w:t xml:space="preserve">' + esc(text) + '</w:t></w:r></w:p>'
}
/** 单元格：把 '\n' 渲染成 <w:br/>（同一 <w:p> 内软换行，真实脚本稿就是这样分行） */
function wCellRun(text) {
  const parts = String(text == null ? '' : text).split('\n')
  let out = '<w:r><w:t xml:space="preserve">' + esc(parts[0]) + '</w:t></w:r>'
  for (let i = 1; i < parts.length; i++) {
    out += '<w:r><w:br/></w:r><w:r><w:t xml:space="preserve">' + esc(parts[i]) + '</w:t></w:r>'
  }
  return out
}
function wCell(text) {
  const body = (text === '' || text == null)
    ? '<w:p/>'
    : '<w:p>' + wCellRun(text) + '</w:p>'
  return '<w:tc><w:tcPr><w:tcW w:w="2400" w:type="dxa"/></w:tcPr>' + body + '</w:tc>'
}
function wRow(cells) { return '<w:tr>' + cells.map(wCell).join('') + '</w:tr>' }
function wTbl(rows) { return '<w:tbl><w:tblPr><w:tblW w:w="0" w:type="auto"/></w:tblPr>' + rows.map(wRow).join('') + '</w:tbl>' }

function buildDoc(spec) {
  let body = ''
  spec.blocks.forEach((b) => {
    if (b.p != null) body += wPara(b.p)
    else if (b.table) body += wTbl(b.table)
  })
  return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">' +
    '<w:body>' + body + '</w:body></w:document>'
}

